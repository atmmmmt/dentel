#!/usr/bin/env node
/**
 * Converts BodyParts3D tooth + gingiva OBJ files (real human CT data) into a compact module
 * used by the 3D dental chart.
 *
 *   node scripts/build-dentition.mjs <path-to-isa_BP3D_4.0_obj_99-folder>
 *
 * Source: "BodyParts3D, (c) The Database Center for Life Science licensed under
 * CC Attribution-Share Alike 2.1 Japan" — https://dbarchive.biosciencedbc.jp/en/bodyparts3d/
 */
import fs from 'node:fs';
import path from 'node:path';

const SRC = process.argv[2];
if (!SRC) { console.error('usage: node scripts/build-dentition.mjs <obj-folder>'); process.exit(1); }

// FDI number → BodyParts3D element file
const FILES = {
  11: 'FJ1279', 12: 'FJ1280', 13: 'FJ1281', 14: 'FJ1277', 15: 'FJ1278', 16: 'FJ1276', 17: 'FJ1275',
  21: 'FJ1265', 22: 'FJ1266', 23: 'FJ1267', 24: 'FJ1262', 25: 'FJ1264', 26: 'FJ1261', 27: 'FJ1263',
  31: 'FJ1258', 32: 'FJ1259', 33: 'FJ1260', 34: 'FJ1255', 35: 'FJ1257', 36: 'FJ1254', 37: 'FJ1256',
  41: 'FJ1272', 42: 'FJ1273', 43: 'FJ1274', 44: 'FJ1269', 45: 'FJ1271', 46: 'FJ1268', 47: 'FJ1270',
  gumU: 'FJ1252', gumL: 'FJ1253',
};

function readObj(id) {
  const txt = fs.readFileSync(path.join(SRC, `${id}.obj`), 'utf8');
  const pos = [], idx = [];
  for (const line of txt.split('\n')) {
    if (line.startsWith('v ')) {
      const [, x, y, z] = line.trim().split(/\s+/).map(Number);
      // BodyParts3D: x = patient left(+)/right(−), y = posterior(+), z = up  →  scene: x, y = up, z = anterior
      pos.push(x, z, -y);
    } else if (line.startsWith('f ')) {
      const v = line.trim().split(/\s+/).slice(1).map(t => parseInt(t, 10) - 1);
      for (let i = 1; i < v.length - 1; i++) idx.push(v[0], v[i], v[i + 1]);
    }
  }
  return { pos, idx };
}

const meshes = {};
for (const [k, id] of Object.entries(FILES)) meshes[k] = readObj(id);

// Global frame: midline x = 0, occlusal contact plane y = 0, incisal point z ≈ 0.
const teethKeys = Object.keys(meshes).filter(k => /^\d+$/.test(k));
const centroid = (m) => { let x = 0, y = 0, z = 0; const n = m.pos.length / 3; for (let i = 0; i < m.pos.length; i += 3) { x += m.pos[i]; y += m.pos[i + 1]; z += m.pos[i + 2]; } return [x / n, y / n, z / n]; };
const bbox = (m) => { const mn = [1e9, 1e9, 1e9], mx = [-1e9, -1e9, -1e9]; for (let i = 0; i < m.pos.length; i += 3) for (let a = 0; a < 3; a++) { mn[a] = Math.min(mn[a], m.pos[i + a]); mx[a] = Math.max(mx[a], m.pos[i + a]); } return { mn, mx }; };
let cx = 0; teethKeys.forEach(k => { cx += centroid(meshes[k])[0]; }); cx /= teethKeys.length;
const upperMinY = Math.min(...teethKeys.filter(k => k < 30).map(k => bbox(meshes[k]).mn[1]));
const lowerMaxY = Math.max(...teethKeys.filter(k => k > 30).map(k => bbox(meshes[k]).mx[1]));
const cy = (upperMinY + lowerMaxY) / 2;
const cz = Math.max(bbox(meshes[11]).mx[2], bbox(meshes[21]).mx[2]);
for (const m of Object.values(meshes)) for (let i = 0; i < m.pos.length; i += 3) { m.pos[i] -= cx; m.pos[i + 1] -= cy; m.pos[i + 2] -= cz; }

// Third molars are not in the dataset: derive them from the second molars (scaled, placed distally).
for (const [w, s, f] of [[18, 17, 16], [28, 27, 26], [38, 37, 36], [48, 47, 46]]) {
  const a = centroid(meshes[f]), b = centroid(meshes[s]);
  const d = [b[0] - a[0], b[1] - a[1], b[2] - a[2]];
  const k = 0.9;
  const src = meshes[s];
  const pos = [];
  for (let i = 0; i < src.pos.length; i += 3) {
    pos.push(b[0] + (src.pos[i] - b[0]) * k + d[0] * 0.93, b[1] + (src.pos[i + 1] - b[1]) * k + (w < 30 ? 0.6 : -0.6), b[2] + (src.pos[i + 2] - b[2]) * k + d[2] * 0.93);
  }
  meshes[w] = { pos, idx: src.idx.slice() };
}

// Quantise to 1/100 mm (Int16) and pack as base64.
const pack = (m) => {
  const p = Int16Array.from(m.pos, v => Math.round(v * 100));
  const i = m.pos.length / 3 > 65535 ? Uint32Array.from(m.idx) : Uint16Array.from(m.idx);
  return { p: Buffer.from(p.buffer).toString('base64'), i: Buffer.from(i.buffer).toString('base64'), i32: i instanceof Uint32Array };
};
const out = {};
// Gingiva is generated procedurally as a denture base (see components/jaw/denture.js), so only teeth are shipped.
for (const [k, m] of Object.entries(meshes)) if (/^\d+$/.test(k)) out[k] = pack(m);

const file = `// Generated by scripts/build-dentition.mjs — do not edit.
// Real human dentition (CT-derived). "BodyParts3D, (c) The Database Center for Life Science
// licensed under CC Attribution-Share Alike 2.1 Japan" — https://dbarchive.biosciencedbc.jp/en/bodyparts3d/
// Units: 1/100 mm (Int16). Frame: x = patient left, y = up (occlusal plane at 0), z = anterior.
export const ATTRIBUTION = 'BodyParts3D © DBCLS — CC BY-SA 2.1 JP';
export const DENTITION = ${JSON.stringify(out)};
`;
const dest = path.resolve('src/components/jaw/dentition.data.js');
fs.writeFileSync(dest, file);
console.log('wrote', dest, (file.length / 1024).toFixed(0), 'KB');
